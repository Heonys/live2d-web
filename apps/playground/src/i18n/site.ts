export const SITE_LOCALES = ['en', 'ko', 'ja'] as const
export type SiteLocale = typeof SITE_LOCALES[number]

export const PREFIXED_SITE_LOCALES = ['ko', 'ja'] as const
export type PrefixedSiteLocale = typeof PREFIXED_SITE_LOCALES[number]

export const languageNames: Record<SiteLocale, string> = {
  en: 'English',
  ja: '日本語',
  ko: '한국어',
}

export function isSiteLocale(value: string): value is SiteLocale {
  return SITE_LOCALES.includes(value as SiteLocale)
}

export function isPrefixedSiteLocale(value: string): value is PrefixedSiteLocale {
  return PREFIXED_SITE_LOCALES.includes(value as PrefixedSiteLocale)
}

export function siteLocaleFromPath(pathname: string): SiteLocale {
  const docs = pathname.match(/^\/docs\/(en|ko|ja)(?:\/|$)/u)
  if (docs?.[1] && isSiteLocale(docs[1]))
    return docs[1]
  const prefix = pathname.match(/^\/(ko|ja)(?:\/|$)/u)
  return prefix?.[1] && isPrefixedSiteLocale(prefix[1]) ? prefix[1] : 'en'
}

export function stripSiteLocale(pathname: string) {
  const stripped = pathname.replace(/^\/(?:ko|ja)(?=\/|$)/u, '')
  return stripped || '/'
}

export function localizedPath(locale: SiteLocale, pathname: string) {
  const normalized = pathname === '' ? '/' : pathname.startsWith('/') ? pathname : `/${pathname}`
  const unprefixed = stripSiteLocale(normalized)
  if (locale === 'en')
    return unprefixed
  return unprefixed === '/' ? `/${locale}` : `/${locale}${unprefixed}`
}

export function localizedDocPath(locale: SiteLocale, slug = '') {
  return `/docs/${locale}${slug ? `/${slug}` : ''}`
}

export function switchLocalePath(pathname: string, locale: SiteLocale) {
  const docs = pathname.match(/^\/docs\/(?:en|ko|ja)(?:\/(.*))?$/u)
  if (docs)
    return localizedDocPath(locale, docs[1] ?? '')

  const unprefixed = stripSiteLocale(pathname)
  if (unprefixed === '/examples')
    return localizedDocPath(locale, 'examples')
  return localizedPath(locale, unprefixed)
}

